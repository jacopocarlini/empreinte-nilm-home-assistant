export function locale(language) {
  return ({ fr: "fr-FR", en: "en-GB", it: "it-IT" })[language] || "fr-FR";
}

export function translate(language, key) {
  return (messages[language] || messages.fr)[key] ?? messages.fr[key] ?? key;
}

export function relativeTime(language, ms, now = Date.now()) {
  const seconds = (now - ms) / 1000;
  if (seconds < 90) return translate(language, "justNow");
  const [amount, unit] = seconds < 3600 ? [Math.round(seconds / 60), "minute"]
    : seconds < 86400 ? [Math.round(seconds / 3600), "hour"]
    : [Math.round(seconds / 86400), "day"];
  return new Intl.RelativeTimeFormat(locale(language), { numeric: "always", style: "short" }).format(-amount, unit);
}
